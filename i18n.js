let LOCALE = 'en';

function setLocale(l) {
    LOCALE = (l === 'en' || I18N[l]) ? l : 'en';
    document.documentElement.lang = LOCALE;
}

function t(key) {
    const dict = I18N[LOCALE];
    return (dict && dict[key]) || key;
}

// app.js renders every table and card through TT(), which reads this.
window.t = t;

// Static markup. data-i18n: original trimmed textContent is the key.
// data-i18n-html: original innerHTML (whitespace-collapsed) is the key, for
// the leaves that carry inline <b>/<code> formatting. data-i18n-placeholder:
// the search box, whose prompt changes per panel but starts here.
function applyStaticI18n() {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
        if (!el.dataset.i18nKey) el.dataset.i18nKey = el.textContent.trim();
        el.textContent = t(el.dataset.i18nKey);
    });
    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
        if (!el.dataset.i18nKey) el.dataset.i18nKey = el.innerHTML.trim().replace(/\s+/g, ' ');
        el.innerHTML = t(el.dataset.i18nKey);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
        if (!el.dataset.i18nKey) el.dataset.i18nKey = el.placeholder;
        el.placeholder = t(el.dataset.i18nKey);
    });
}

function currentFleetLang() { return (window.CarinoLang && window.CarinoLang.current) || 'en'; }

function applyI18n() {
    setLocale(currentFleetLang());
    applyStaticI18n();
    // Re-render the JS-generated surfaces (tables, cards, totals). app.js may
    // still be fetching data/ on first paint, hence the guard.
    if (window.OFFLINE && typeof window.OFFLINE.render === 'function') window.OFFLINE.render();
}

// carino-lang.js is deferred and runs before this (also deferred) script, so
// CarinoLang exists by DOMContentLoaded; re-apply on every fleet switch.
document.addEventListener('DOMContentLoaded', applyI18n);
window.addEventListener('carino:langchange', applyI18n);
